import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoEqualEarth, geoPath } from "d3-geo";
import { feature } from "topojson-client";
import countries from "i18n-iso-countries";

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
const WIDTH = 1000;
const HEIGHT = 500;

const land = feature(topology, topology.objects.countries);
land.features = land.features.filter((f) => f.id !== "010");
const projection = geoEqualEarth().fitSize([WIDTH, HEIGHT], land);
const path = geoPath(projection).digits(1);

const shapes = {};
const rest = [];
for (const f of land.features) {
  const code = f.id ? countries.numericToAlpha2(f.id) : undefined;
  const d = path(f);
  if (!d) continue;
  if (code) shapes[code] = d;
  else rest.push(d);
}

const lines = Object.keys(shapes)
  .sort()
  .map((code) => `  ${code}: "${shapes[code]}",`)
  .join("\n");

writeFileSync(
  new URL("../src/map/world.ts", import.meta.url),
  `/** Country outlines by ISO 3166-1 alpha-2 code, on a ${WIDTH} by ${HEIGHT} canvas. Generated by scripts/build-world.mjs from Natural Earth 1:110m (public domain); do not edit. */
export const WORLD_SIZE = { width: ${WIDTH}, height: ${HEIGHT} } as const;

export const COUNTRIES: Readonly<Record<string, string>> = {
${lines}
};

/** Land that has no country code of its own, drawn but never selectable. */
export const UNCODED = "${rest.join("")}";
`,
);
console.log(`${Object.keys(shapes).length} countries, ${rest.length} uncoded`);
